-- gamedata.db: static, read-only game content -- Items, Mobs, drop tables,
-- exp curve, skills, item-mall catalog. Ships pre-built alongside the
-- release; the running server never writes to this file. A content update
-- is just replacing this one file, no player-data migration involved.
--
-- Column names mirror the original SQL Server schema exactly (confirmed
-- real names, several found the hard way this session: `Slot` not `Slots`,
-- `ReqLevel` not `Level`, no `RealType` column at all).

PRAGMA journal_mode = WAL;

CREATE TABLE IF NOT EXISTS Items (
    Type      INTEGER NOT NULL,
    TypeID    INTEGER NOT NULL,
    Effect1   INTEGER NOT NULL DEFAULT 0,
    Effect2   INTEGER NOT NULL DEFAULT 0,
    Effect3   INTEGER NOT NULL DEFAULT 0,
    Effect4   INTEGER NOT NULL DEFAULT 0,
    ConstHP   INTEGER NOT NULL DEFAULT 0,
    ConstSP   INTEGER NOT NULL DEFAULT 0,
    ConstMP   INTEGER NOT NULL DEFAULT 0,
    ConstStr  INTEGER NOT NULL DEFAULT 0,
    ConstDex  INTEGER NOT NULL DEFAULT 0,
    ConstRec  INTEGER NOT NULL DEFAULT 0,
    ConstInt  INTEGER NOT NULL DEFAULT 0,
    ConstWis  INTEGER NOT NULL DEFAULT 0,
    ConstLuc  INTEGER NOT NULL DEFAULT 0,
    ReqWis    INTEGER NOT NULL DEFAULT 0,
    Server    INTEGER NOT NULL DEFAULT 0,
    Slot      INTEGER NOT NULL DEFAULT 0,
    ReqLevel  INTEGER NOT NULL DEFAULT 0,
    ReqInt    INTEGER NOT NULL DEFAULT 0,
    ReqLuc    INTEGER NOT NULL DEFAULT 0,
    Special   INTEGER NOT NULL DEFAULT 0,
    ReqIg     INTEGER NOT NULL DEFAULT 0,
    AttackTime INTEGER NOT NULL DEFAULT 0,
    Range     REAL NOT NULL DEFAULT 0,
    Quality   INTEGER NOT NULL DEFAULT 0,
    Count     INTEGER NOT NULL DEFAULT 1,
    Sell      INTEGER NOT NULL DEFAULT 0,
    Grade     INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (Type, TypeID)
);
CREATE INDEX IF NOT EXISTS idx_items_grade ON Items(Grade);

CREATE TABLE IF NOT EXISTS MobItems (
    MobID     INTEGER NOT NULL,
    ItemOrder INTEGER NOT NULL,
    Grade     INTEGER NOT NULL DEFAULT 0,
    DropRate  INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (MobID, ItemOrder)
);

CREATE TABLE IF NOT EXISTS Mobs (
    MobID          INTEGER PRIMARY KEY,
    Level          INTEGER NOT NULL DEFAULT 1,
    HP             INTEGER NOT NULL DEFAULT 100,
    Money1         INTEGER NOT NULL DEFAULT 0,
    Money2         INTEGER NOT NULL DEFAULT 0,
    AttackSpecial3 INTEGER NOT NULL DEFAULT 0,
    Exp            INTEGER NOT NULL DEFAULT 0,
    Attack1        INTEGER NOT NULL DEFAULT 0,
    AI             INTEGER NOT NULL DEFAULT 0,
    ChaseRange     REAL NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ExpDefs (
    Level INTEGER NOT NULL,
    Grow  INTEGER NOT NULL,
    Exp   INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (Level, Grow)
);

